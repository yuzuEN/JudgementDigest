"""
使用者的口語描述 → 判決書用語，只用在平台的輸入（訓練資料本來就是判決書用語，不經過這裡）。

模型和檢索都是用判決書文字訓練的，一個字的差別就差很多：「我在超商偷了兩瓶飲料」第一個罪名是毀損罪（機率 .01），
「偷」換成「竊取」就是竊盜罪（.98）。這裡只換意思明確、判決書固定用的詞。16 句自編口語例句（酒駕、竊盜、傷害、詐欺、殺人…各一句）的第一個罪名，
轉換前猜中 12 句、轉換後 15 句（詐欺「收錢沒寄票」仍猜成洗錢）。
"""
import re
from typing import List, Tuple

# （規則, 換成）；依序套用，前面的先換
RULES: List[Tuple[str, str]] = [
    (r"小偷", "竊賊"),
    (r"(?<!偷)偷(?:走|拿|了)?(?!偷)", "竊取"),
    (r"(?<![詐欺])騙(?:了|走)?", "詐騙"),
    (r"搶(?:走|了)", "搶奪"),
    (r"揍", "毆打"),
    (r"(?:拿|持)刀砍", "持刀砍殺"),
    (r"差點(?:死掉|死了|被打死)", "經送醫救治始未發生死亡之結果"),
    (r"(?:沒有|沒)(?:停下來|停車|下車)?(?:就)?(?:直接)?(?:開走|騎走|跑走|離開)", "逃逸"),
    (r"打(?=(?:了)?(?:他|她|我|人|對方|一拳|一巴掌|巴掌|耳光|頭|臉))", "毆打"),
    (r"罵(?!人的話)", "辱罵"),
    (r"威脅", "恐嚇"),
    (r"吸毒|吸安|拉[Kk]", "施用毒品"),
    (r"喝(?:了)?酒", "飲酒"),
    (r"喝了", "飲用"),
    (r"騎(?:機)?車", "騎乘機車"),
    (r"開車", "駕駛車輛"),
    (r"撞(?:到|傷)", "撞擊"),
    (r"驗傷", "就醫診斷"),
    (r"報警", "報警處理"),
    (r"(?:借|給|賣)(?:給)?(?=[^，。]{0,6}(?:帳戶|帳號|存摺|提款卡))", "交付"),
    (r"((?:帳戶|帳號|存摺|提款卡|密碼)[^，。]{0,4}?)(?:借|賣)?給", r"\1交付"),
    (r"我們", "被告等"),
    # 「我哥哥」「我的手機」不換：那是別人或東西，不是被告
    (r"我(?!的|們|哥|姐|姊|弟|妹|爸|媽|家|老公|老婆|太太|先生|女友|男友|朋友|同事|鄰居)", "被告"),
]
COMPILED = [(re.compile(p), r) for p, r in RULES]


def to_legal(text: str) -> str:
    for pattern, repl in COMPILED:
        text = pattern.sub(repl, text)
    return text
