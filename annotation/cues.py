"""
手冊 v0.3 列出的線索詞，抽樣（sample.py）與抽查（spot_check.py）共用。

兩個用途：
  1. 加抽：DAM、SUB 在隨機樣本裡太少（約 1–2% 的段落），先用線索篩出可能的段落再抽，湊夠抽查的數量
  2. 抽查：模型標了某個標籤時，自動檢查段落裡有沒有手冊列出的線索，人工只需要判斷有疑問的

線索只用來「找」和「提示」，不是標籤本身：有線索不代表一定是該標籤（例如「送達」多半是利息起算日）。
改這裡的線索時，請一併更新《論點標註手冊》對應的表格。
"""
import re

CUES = {
    # 給付額酌定：慰撫金核定、過失相抵、損害額酌定、違約金酌減、以公平原則定金額
    "DAM": re.compile(
        r"慰撫金.{0,80}(?:審酌|斟酌|酌定|核定|為適當|相當)|(?:審酌|斟酌).{0,80}慰撫金"
        r"|與有過失|過失相抵|民法第217條"
        r"|民事訴訟法第222條第2項|依所得心證定其數額"
        r"|違約金.{0,40}(?:酌減|過高|核減)"
        r"|始符公平"),
    # 涵攝（窄定義）：要件判斷、定性
    "SUB": re.compile(
        r"(?:該當|合於|符合|不符|未符|構成).{0,20}(?:要件|構成要件)|構成要件.{0,10}(?:該當|不該當)"
        r"|(?:即屬|核屬|自屬|應屬).{0,20}(?:侵權行為|不當得利|借名登記|詐欺|違約|債務不履行)"
        r"|核.{0,30}所為.{0,10}係犯"),
    # 送達：用來加抽「送達」段落，檢查模型有沒有守住窄定義（利息起算日不標 PROC）
    "SERVICE": re.compile(r"送達"),
    # 證據評價用語（手冊 v0.3 的 EV 判準）
    "EV": re.compile(
        r"堪信|可採|足認|堪認|應堪認定|相符|互核一致|非虛|可資佐證"
        r"|不足採|無可採|不可採|難認|尚難|無足取|顯有疑義|難以採信|前後不一"
        r"|尚無法證明|不能證明"),
}

# 「送達」只用於利息起算的寫法：出現這種寫法的段落，模型不應該只因為「送達」就標 PROC
INTEREST_SERVICE = re.compile(r"(?:起訴狀|支付命令|準備書狀).{0,6}繕本送達(?:之)?翌日起")


def cue_hits(text: str) -> list:
    """段落中出現哪些線索（CUES 的 key）。"""
    return [k for k, rx in CUES.items() if rx.search(text or "")]
