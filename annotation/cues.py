# 規則 10「引文必須是完成該動作的那一句」的自動檢查：各標籤的引文應含有的動作用語。
# 用來找出「標籤對、引文錯」的可疑列（例如 EV 只引到列舉證據的部分），不是用來決定標籤。
QUOTE_ACT = {
    "EV": CUES["EV"],
    # 「須符合」「應符合」「如該當」是條件（大前提）；「構成要件」是名詞，都不算定性結論
    # v0.5：「即屬有據」「核屬有理」移到 CONCL，SUB 只收定性
    "SUB": re.compile(r"係犯|(?:核屬|即屬|自屬|應屬)(?!有據|有理)|即為|構成(?!要件)"
                      r"|(?<![須需應如若倘])(?:該當|符合|合於|不符|未符|不相符)"
                      r"|難認.{0,20}(?:行為|責任|要件)|無法律上之?原因|應負.{0,15}責任|不負.{0,15}責任"
                      # v0.5：「堪認／應認」接法律評價、定性用的「屬」，以及常見的法律效果用語
                      r"|(?:堪|應|足|可)認|(?:係|當|顯|即|亦|均|要|仍|非)屬(?!有據|無據|有理|實)|屬於|屬有害"
                      r"|侵害|不法|情節重大|與有過失|侵權行為|成立|無效|推定|視為|罹於|時效|無權占有|妨害"
                      r"|(?:不得|無從|自得)(?:主張|請求|依)|顯失公平|免責|拘束|難謂|甚明|至明"),
    "RULE": re.compile(r"按|所謂|係指|定有明文|規定|者[，,]|倘|如|若"
                       # v0.5 試標補充：「應斟酌⋯⋯」「以⋯⋯為成立要件」「在所不問」「不以⋯⋯為必要」
                       r"|應斟酌|為(?:成立)?要件|在所不問|不以.{0,10}為必要|始能|乃|指|範疇|由.{0,6}法院"),
    "DAM": re.compile(r"元|適當|相當|酌減|核減|減輕|過失|酌定|核定|審酌|斟酌"),
    "CONCL": CUES["CONCL"],
    "EXP": CUES["EXP"],
    "PROC": re.compile(r"假執行|擔保|逕行判決|一造辯論|駁回|不合法|確認利益|即受確認判決|送達|裁判費|訴訟費用"
                       r"|聲明|既判力|當事人適格|管轄|上訴|補正|逾期|審判範圍|程序"),
}

# 「送達」只用於利息起算的寫法：出現這種寫法的段落，模型不應該只因為「送達」就標 PROC
INTEREST_SERVICE = re.compile(r"(?:起訴狀|支付命令|準備書狀).{0,6}繕本送達(?:之)?翌日起")


def cue_hits(text: str) -> list:
    """段落中出現哪些線索（CUES 的 key）。"""
    return [k for k, rx in CUES.items() if rx.search(text or "")]


MARK = "〔略〕"   # v0.6：引文超過 100 字時，寫「開頭〔略〕結尾」
HEAD_MARKED = ("RULE", "EXP")   # 標記用語常在開頭的標籤：錨定檢查看開頭＋結尾


def quote_anchored(label: str, quote: str):
    """
    引文是否含該標籤的動作用語：True／False；該標籤沒有定義檢查時回傳 None。
    v0.6：引文用了〔略〕時，只看模型寫出來的字，不看程式補出來的中間，不然範圍一長幾乎一定會含有某個用語。
      - 結論在句尾的標籤（CONCL、DAM、SUB、EV⋯⋯）：只檢查結尾（手冊規則三：完成動作的用語寫在結尾）
      - RULE、EXP：標記用語常在開頭（「按」「所謂」「衡諸常情，⋯⋯」），開頭和結尾都檢查
        （v0.6 試標：RULE 只看結尾 72.4%，開頭＋結尾 86.2%）
    """
    rx = QUOTE_ACT.get(label)
    if rx is None:
        return None
    parts = (quote or "").split(MARK)
    text = " ".join(parts) if label in HEAD_MARKED else parts[-1]
    return bool(rx.search(text))
