"""
手冊 v0.5 列出的線索詞，抽樣（sample.py）與抽查（spot_check.py）共用。

兩個用途：
  1. 加抽：DAM、SUB、EXP 在隨機樣本裡太少，先用線索篩出可能的單位再抽，湊夠抽查的數量
  2. 抽查：模型標了某個標籤時，自動檢查段落裡有沒有手冊列出的線索，人工只需要判斷有疑問的

線索只用來「找」和「提示」，不是標籤本身：有線索不代表一定是該標籤（例如「送達」多半是利息起算日）。
改這裡的線索時，請一併更新《論點標註手冊》對應的表格。
"""
import re

CUES = {
    # 給付額酌定：慰撫金核定、過失相抵、損害額酌定、違約金酌減、以公平原則定金額
    "DAM": re.compile(
        r"慰撫金.{0,80}(?:審酌|斟酌|酌定|核定|為適當|相當)|(?:審酌|斟酌).{0,80}慰撫金"
        r"|與有過失|過失相抵|民法第217條"
        r"|民事訴訟法第222條第2項|依所得心證定其數額"
        r"|違約金.{0,40}(?:酌減|過高|核減)"
        r"|始符公平"),
    # 涵攝（窄定義）：要件判斷、定性
    "SUB": re.compile(
        r"(?:該當|合於|符合|不符|未符|構成).{0,20}(?:要件|構成要件)|構成要件.{0,10}(?:該當|不該當)"
        # v0.5：「即屬有據」「自屬有據」「核屬有理」是請求判斷（CONCL），不是定性，用 (?!有據|有理) 排除
        r"|(?:即屬|核屬|自屬|應屬)(?!有據|有理).{0,20}(?:侵權行為|不當得利|借名登記|詐欺|違約|債務不履行)"
        r"|核.{0,30}所為.{0,10}係犯"),
    # 送達：用來加抽「送達」段落，檢查模型有沒有守住窄定義（利息起算日不標 PROC）
    "SERVICE": re.compile(r"送達"),
    # 證據評價用語（手冊 v0.4 的 EV 判準；v0.4 補足見、益徵、顯見、足證、勘驗屬實）
    "EV": re.compile(
        # 「核與證人所述相符」是評價；「提出與其所述相符之借據」的相符之是修飾證據，屬列舉
        r"堪信|可採|足認|堪認|應堪認定|相符(?!之)|互核一致|非虛|可資佐證"
        r"|足見|益徵|顯見|足證|勘驗屬實"
        # v0.5：依證據推論（可知、可見、足徵）也算 EV，子欄位 basis 記為「依證據推論」
        r"|足徵|可知|可見|屬實|吻合"
        r"|不足採|無足採|無可採|不可採|難認|尚難|無足取|顯有疑義|難以採信|前後不一"
        r"|尚無法證明|不能證明|難證明|無從.{0,6}認"),
    # 請求判斷（v0.5 新增 CONCL）：法院對請求有沒有理由的結論。這些用語 v0.4 以前算在 SUB 的結論裡
    "CONCL": re.compile(
        r"為有理由|為無理由|一部有理由|應予准許|應予駁回|不應准許|不應予准許"
        r"|即屬有據|洵屬有據|於法有據|自屬有據|即無不合|核屬有理"),
    # 經驗法則（v0.5：封閉清單，一般經驗陳述也標 EXP）
    "EXP": re.compile(r"經驗法則|論理法則|屢見不鮮|眾所周知|一般人均知|依社會通念|社會通念|依一般經驗|常情|事理之常"),
    # 大前提（v0.4 新增 RULE）
    "RULE": re.compile(r"(?:^|[、：:）)\s])(?:次|又|復|再|惟|另|末)?按|所謂.{0,30}係指|定有明文"),
}

# 規則 10「引文必須是完成該動作的那一句」的自動檢查：各標籤的引文應含有的動作用語。
# 用來找出「標籤對、引文錯」的可疑列（例如 EV 只引到列舉證據的部分），不是用來決定標籤。
QUOTE_ACT = {
    "EV": CUES["EV"],
    # 「須符合」「應符合」「如該當」是條件（大前提）；「構成要件」是名詞，都不算定性結論
    # v0.5：「即屬有據」「核屬有理」移到 CONCL，SUB 只收定性
    "SUB": re.compile(r"係犯|(?:核屬|即屬|自屬|應屬)(?!有據|有理)|即為|構成(?!要件)"
                      r"|(?<![須需應如若倘])(?:該當|符合|合於|不符|未符)"
                      r"|難認.{0,20}(?:行為|責任|要件)|無法律上原因|應負.{0,15}責任|不負.{0,15}責任"),
    "RULE": re.compile(r"按|所謂|係指|定有明文|規定|者[，,]|倘|如|若"),
    "DAM": re.compile(r"元|適當|相當|酌減|核減|減輕|過失|酌定|核定|審酌|斟酌"),
    "CONCL": CUES["CONCL"],
    "EXP": CUES["EXP"],
    "PROC": re.compile(r"假執行|擔保|逕行判決|一造辯論|駁回|不合法|確認利益|即受確認判決|送達|裁判費|訴訟費用"
                       r"|聲明|既判力|當事人適格|管轄|上訴|補正|逾期|審判範圍|程序"),
}

# 「送達」只用於利息起算的寫法：出現這種寫法的段落，模型不應該只因為「送達」就標 PROC
INTEREST_SERVICE = re.compile(r"(?:起訴狀|支付命令|準備書狀).{0,6}繕本送達(?:之)?翌日起")


def cue_hits(text: str) -> list:
    """段落中出現哪些線索（CUES 的 key）。"""
    return [k for k, rx in CUES.items() if rx.search(text or "")]


def quote_anchored(label: str, quote: str):
    """引文是否含該標籤的動作用語：True／False；該標籤沒有定義檢查時回傳 None。"""
    rx = QUOTE_ACT.get(label)
    return None if rx is None else bool(rx.search(quote or ""))
