import re

# 描述裡完全沒有這些字、也沒有金額時，多半不是法律糾紛（模型和檢索不會判斷，什麼內容都會給結果）
_SIGNAL = re.compile(
    r"法院|提告|告他|告我|被告|起訴|訴訟|律師|賠償?|欠|還錢|還我|沒還|不還|歸還|退還|退錢|借|租|押金|薪|工資|加班|資遣|解僱|開除|離職|"
    r"契約|合約|違約|解約|撞|車禍|受傷|傷害|骨折|打我|打傷|辱罵|罵我|毀謗|名譽|騙|詐|匯款|轉帳|土地|過戶|繼承|遺產|遺囑|漏水|"
    r"理賠|損失|損害|侵占|竊|恐嚇|酒駕|酒測|警察|報警|報案|檢察官|傳票|筆錄|和解|調解|存證信函|債|本票|支票|強制執行|離婚|外遇|"
    r"瑕疵|保固|退貨|欠款|貨款|工程款|占用|違建|拆除")
_MONEY = re.compile(r"\d[\d,]*\s*(?:元|萬)|[一二三四五六七八九十百千兩]+萬")


def looks_like_dispute(text: str) -> bool:
    return bool(_SIGNAL.search(text) or _MONEY.search(text))
