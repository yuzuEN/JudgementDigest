"""
追問（第一版：固定題庫）：依案件類型與糾紛類型，問使用者描述裡常漏掉、判決又常用到的事實。
之後改由 LLM 依描述內容追問（API 不變，回傳的 source 會是 "llm"）。
"""
import re
from typing import Dict, List, Optional

# (id, 問題, 為什麼問, 描述裡已經有這些字就不問)
GENERAL = [
    ("when", "這件事是什麼時候發生的？之後經過多久？", "時間會影響請求權有沒有過時效。", r"\d+年|\d+月|去年|今年|前年|上個?月"),
    ("loss", "你受到哪些損失？各大約多少錢？", "判准金額通常是逐項計算的。", r"\d+\s*萬|\d{4,}\s*元|損失|費用"),
    ("other_side", "對方有沒有說過什麼，例如認為你也有責任、或覺得金額太高？", "相似案件中，對方常這樣抗辯。", r"對方說|他說|認為我|聲稱"),
]
BY_MID = [
    (r"交通事故|傷害", [
        ("signal", "事故發生時，你是直行還是轉彎？當時的號誌是什麼燈？", "法院會依雙方的過失比例減少賠償。", r"直行|轉彎|紅燈|綠燈|號誌"),
        ("injury", "你受了什麼傷？住院或休養了多久？", "醫療費、看護費、工作損失都和傷勢有關。", r"骨折|住院|受傷|休養"),
        ("insurance", "有沒有領到強制險或其他保險的理賠？", "已領的強制險理賠通常要從賠償中扣除。", r"強制險|保險|理賠"),
    ]),
    (r"借貸|借款|金融", [
        ("proof", "借錢的時候有沒有寫借據、本票，或用匯款交付？", "法院常要求證明「有借貸的合意」與「交付了錢」。", r"借據|本票|匯款|轉帳"),
        ("repay", "對方有沒有還過一部分？最後一次是什麼時候？", "部分清償會影響請求的金額與時效。", r"還了|還過|清償|償還"),
    ]),
    (r"契約|買賣|承攬|工程", [
        ("terms", "你們有沒有書面契約？約定的內容（價金、期限、規格）是什麼？", "是否違約要看契約怎麼約定。", r"契約|合約|約定"),
        ("perform", "你自己這邊的義務做完了嗎？有沒有驗收或通知對方？", "對方常抗辯你也沒有履行契約。", r"驗收|交貨|完工|通知"),
    ]),
    (r"勞動|工資|資遣|退休", [
        ("period", "你在那裡工作了多久？每月薪資大約多少？", "資遣費、退休金依年資與薪資計算。", r"\d+年|年資|薪水|薪資|月薪"),
        ("end", "是怎麼離職的？公司有沒有給書面的終止通知？", "終止的原因會影響可以請求的項目。", r"資遣|解僱|離職|開除"),
    ]),
    (r"不動產|房屋|租", [
        ("register", "房屋或土地登記在誰的名下？有沒有租約或使用的約定？", "所有權與使用權是這類案件的核心。", r"登記|名下|租約|所有權"),
    ]),
]
CRIMINAL = [
    ("act", "能不能依時間順序描述當時的行為：誰、在哪裡、做了什麼？", "罪名主要依行為的內容判斷。", r""),
    ("result", "造成了什麼結果，例如受傷的程度、財物的損失？", "結果的輕重會影響罪名與刑期。", r"受傷|骨折|損失|死亡"),
    ("settle", "雙方有沒有和解或談過賠償？", "和解與犯後態度是量刑的重要因素。", r"和解|賠償|道歉"),
]


def questions(case_type: str, mid: Optional[str], text: str, limit: int = 4) -> List[Dict]:
    pool = []
    if case_type in ("criminal", "unsure"):
        pool += CRIMINAL
    if case_type in ("civil", "unsure"):
        for rx, qs in BY_MID:
            if mid and re.search(rx, mid):
                pool += qs
                break
        pool += GENERAL
    text = text or ""
    picked, seen = [], set()
    for qid, q, why, answered in pool:
        if qid in seen or (answered and re.search(answered, text)):
            continue
        seen.add(qid)
        picked.append({"id": qid, "text": q, "why": why})
    return picked[:limit]
